// Exercise the actual chooser, practice handlers and answer journal together.
import assert from 'node:assert/strict';
import {bootBrowser,hub,course,flush,Server} from './progress-test-helpers.mjs';
const boot=async options=>{const app=bootBrowser(options);await flush();return app;};
const [scalar,variable,fn]=course.concepts;
const savedView=app=>[...app.storage.entries()].filter(([k])=>k.endsWith(':guest:view')).map(([,v])=>JSON.parse(v))[0];
const row=(app,c)=>app.get('review-topics').innerHTML.split('<tr>').find(s=>s.includes(`id="review-topic-${c.legacyId}"`))||'';
const chosen=(app,c)=>new RegExp(`value="${c.legacyId}"[^>]* checked`).test(row(app,c));
const count=app=>app.get('review-selection-count').textContent;
const stats=(app,c)=>[...row(app,c).matchAll(/<td><span[^>]*>[^<]*<\/span>([^<]*)<\/td>/g)].map(m=>m[1]);

const fresh=await boot();const first=fresh.question().id;
fresh.review();
assert.equal(fresh.get('review-chooser').hidden,false);
assert.equal(fresh.get('quiz-panel').hidden,true,'Review opens the overview, not a question');
assert.equal((fresh.get('review-topics').innerHTML.match(/name="review-topic"/g)||[]).length,128);
assert.equal((fresh.get('review-topics').innerHTML.match(/class="review-chapter"/g)||[]).length,course.chapters.length);
assert.deepEqual(stats(fresh,scalar),['0/10','—','—']);
assert.match(row(fresh,scalar),/Not tried/);assert.doesNotMatch(row(fresh,scalar),/Looking solid|Worth revisiting/);
assert.equal(chosen(fresh,scalar),true,'new learner defaults to the current concept');
fresh.clearTopics();assert.equal(fresh.get('review-start').disabled,true);fresh.startReview();
assert.equal(fresh.get('quiz-panel').hidden,true);
fresh.selectTopic(variable.legacyId);fresh.startReview();
assert.equal(fresh.get('quiz-panel').hidden,false,'an untried selected concept is available');
assert.ok(variable.questions.some(q=>q.id===fresh.question().id));
fresh.correct();fresh.back();assert.equal(fresh.question().id,first);
console.log('PASS: all chapters/topics, neutral untried stats, explicit selection, disabled empty start, and practice of untried topics.');

const app=await boot();
