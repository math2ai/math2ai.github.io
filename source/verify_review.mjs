app.review();assert.deepEqual(stats(app,scalar),['3/10','2/3','3/3']);
assert.doesNotMatch(row(app,scalar),/Looking solid/);
app.back();app.another();app.correct();app.another();
app.go(1);app.wrong();const missed=app.question();
app.go(0);const lesson=app.question();app.draft(2);app.scroll(540);const before=savedView(app);
app.review();
assert.deepEqual(stats(app,scalar),['4/10','3/4','4/4']);assert.match(row(app,scalar),/Looking solid/);
assert.deepEqual(stats(app,variable),['1/10','0/1','0/1']);assert.match(row(app,variable),/Worth revisiting/);
assert.equal(chosen(app,variable),true);assert.equal(chosen(app,scalar),false,'suggestions prioritize latest mistakes');
app.selectTopic(scalar.legacyId);assert.equal(count(app),'2 topics selected');
app.filterReview('solid');assert.ok(row(app,scalar));assert.equal(row(app,variable),'');assert.equal(count(app),'2 topics selected');
app.searchReview('no such topic');assert.equal(app.get('review-no-matches').hidden,false);
assert.equal(count(app),'2 topics selected');assert.equal(app.get('review-start').disabled,false,'hidden selections stay available');
app.startReview();assert.equal(app.question().id,missed.id);assert.equal(app.get('feedback').hidden,true);
app.correct();app.correct();assert.equal(app.state().concepts[variable.legacyId].answers[missed.id].attempts,2);
assert.deepEqual(savedView(app),before,'selection and review answers never replace lesson navigation');
const seen=new Set([missed.id]);
for(let i=0;i<19;i++){
 app.another();const q=app.question();assert.ok(!seen.has(q.id));seen.add(q.id);
 assert.ok([scalar,variable].some(c=>c.questions.some(x=>x.id===q.id)),'selection bounds every question');
 if(i===0)assert.ok(scalar.questions.some(x=>x.id===q.id),'mix concepts rather than exhausting one');
}
const last=app.question().id;app.another();assert.notEqual(app.question().id,last);
app.back();assert.equal(app.question().id,lesson.id);assert.match(app.get('choices').innerHTML,/value="2" checked/);
assert.equal(app.scrollPosition(),540);assert.deepEqual(savedView(app),before);
console.log('PASS: first/latest denominators, strengths, filtered-out choices, selected-pool rotation, exact lesson/deck/draft/scroll return.');

app.review();app.clearTopics();app.searchReview('scalar');app.selectChapter(0);
assert.equal(count(app),'1 topic selected');assert.equal(chosen(app,scalar),true,'chapter selection respects search');
app.selectChapter(0);assert.equal(count(app),'0 topics selected');
app.searchReview('');app.selectChapter(0);
const chapterSize=course.concepts.filter(c=>c.chapter===scalar.chapter).length;
assert.equal(count(app),`${chapterSize} topics selected`);app.selectChapter(0);assert.equal(count(app),'0 topics selected');
app.selectTopic(fn.legacyId);app.filterReview('selected');assert.ok(row(app,fn));assert.equal(row(app,scalar),'');
app.selectTopic(fn.legacyId,false);assert.equal(app.get('review-no-matches').hidden,false);
app.filterReview('all');app.suggestTopics();
assert.equal(chosen(app,scalar),true);assert.equal(chosen(app,variable),true,'with no latest mistakes, suggest practiced topics');
app.clearTopics();app.selectTopic(fn.legacyId);app.startReview();const draft=app.question();app.draft(1);
app.changeTopics();assert.equal(app.get('quiz-panel').hidden,true);assert.equal(app.get('review-start').textContent,'Resume review');
app.startReview();assert.equal(app.question().id,draft.id);assert.match(app.get('choices').innerHTML,/value="1" checked/);
app.answer(draft.correct);app.changeTopics();app.startReview();assert.equal(app.get('feedback').hidden,false);
app.changeTopics();app.clearTopics();app.selectTopic(variable.legacyId);assert.equal(app.get('review-start').textContent,'Start review');
app.startReview();assert.ok(variable.questions.some(q=>q.id===app.question().id));assert.equal(app.get('feedback').hidden,true);
app.back();app.review();assert.equal(count(app),'1 topic selected');assert.equal(chosen(app,variable),true);
const reload=await boot({shared:hub(app.storage),hash:'#review'});
assert.equal(reload.get('review-chooser').hidden,false);assert.equal(chosen(reload,variable),true);
reload.hash('#lesson-'+fn.legacyId);assert.equal(reload.current().legacyId,fn.legacyId);
reload.review();reload.hash('');assert.equal(reload.get('review-panel').hidden,true);
console.log('PASS: chapter scope, presets, change/resume preserves drafts and feedback, changed scope restarts, selection survives reopening/reload.');

