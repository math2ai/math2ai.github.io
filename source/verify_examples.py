"""Independent arithmetic checks for the revised worked examples."""
from pathlib import Path
import json, math
course=json.loads((Path(__file__).parent/'dist/curriculum.json').read_text(encoding='utf-8'))
by_title={c['title']:c for c in course['concepts']}
checks=[]
def check(title,actual,expected,needle,tol=1e-10):
    assert math.isclose(actual,expected,rel_tol=tol,abs_tol=tol),(title,actual,expected)
    assert needle in by_title[title]['example'],(title,needle)
    checks.append(title)

t=[[[1,2],[3,4]],[[5,6],[7,8]]]
check('Tensor',t[1][0][1],6,'T₂₁₂ = 6')
check('Matrix multiplication',sum(a*b for a,b in zip([1,2],[5,6])),17,'= 17')
check('Matrix multiplication',sum(a*b for a,b in zip([3,4],[5,6])),39,'= 39')
check('Linear transformation',sum(a*b for a,b in zip([0,3],[1,2])),6,'(2, 6)')
check('Variance',sum((x-4)**2 for x in [2,6])/2,4,'= 4')
check('Exponential and logarithm',math.log(8,2),3,'log₂(8) = 3')
check('Exponential and logarithm',math.log(7.389),2,'≈ 2',tol=1e-5)
check('Derivative',(3.01**2-3**2)/.01,6.01,'= 6.01')
check('Chain rule',2*(2*3)*2,24,'= 24')
check('Gradient descent',(3-.1*2*3)**2,5.76,'= 5.76')
check('Linear regression',2*5+3,13,'$13')
check('Artificial neuron',3*2-2*1+1,5,'= 5')
check('Sigmoid',1/(1+math.exp(-2)),.881,'≈ 0.881',tol=.001)
check('Forward pass',(1*2-6)**2,16,'= 16')
check('Backpropagation',2*(1*2-6)*2,-16,'= −16')
check('Mini-batch gradient descent',1-.1*sum([2,6])/2,.6,'= 0.6')
check('Deep neural network',3*max(0,max(0,2*2-1)-1),6,'= 6')
check('Cross-entropy',-math.log(.9),.105,'≈ 0.105',tol=.001)
check('Cross-entropy',-math.log(.1),2.303,'≈ 2.303',tol=.001)
check('Self-supervised learning',(5-4)**2,1,'= 1')
check('Embedding',math.dist((1,0),(.9,.1)),.14,'≈ 0.14',tol=.005)
check('Embedding',math.dist((1,0),(0,1)),1.41,'≈ 1.41',tol=.005)
check('Principal component analysis',sum(v/math.sqrt(2) for v in [-1,-1]),-math.sqrt(2),'−√2')
check('Autoencoder',sum((a-b)**2 for a,b in zip([2,5],[2,4]))/2,.5,'= 0.5')
check('Bit and byte',2**8,256,'= 256')
check('Rate-distortion tradeoff',2+.1*5,2.5,'2.5')
check('Vector quantization',math.dist((1,2),(0,2)),1,'are 1 and 2')
check('Vector-quantized autoencoder',sum((a-b)**2 for a,b in zip([2,5],[2,4]))/2,.5,'= 0.5')
x=[1,3,1,3];mu=sum(x)/len(x)
r=sum((a-mu)*(b-mu) for a,b in zip(x,x[1:]))/sum((a-mu)**2 for a in x)
check('Sequence and autocorrelation',r,-.75,'= −0.75')
weights=[math.exp(z)/(1+3) for z in [0,math.log(3)]]
check('Scaled dot-product attention',sum(a*b for a,b in zip(weights,[2,6])),5,'= 5')
check('Multi-head attention',.5*(.25*2+.75*6)+.5*(.75*2+.25*6),4,'give 4')
check('Causal mask',math.exp(-math.inf),0,'(0.5, 0.5, 0)')
h=[1+1,3+1];mean=sum(h)/2;sd=math.sqrt(sum((a-mean)**2 for a in h)/2)
check('Transformer',(h[0]-mean)/sd,-1,'(−1, 1)')
check('API and SDK',sum([2,4,6])/3,4,'returns 4')
check('Markov decision process',.9+.1,1,'probability 0.1')
check('Bellman equation',2+.9*(.5*10+.5*0),6.5,'= 6.5')
check('Q-learning',2+.25*(1+.5*6-2),2.5,'= 2.5')
check('Policy gradient',.5+.1*(4-1),.8,'= 0.8')
check('Model predictive control',10+6-2,14,'target 14 L')
check('Model predictive control',13+3-2,14,'3 L')
check('RLHF',.75*2+.25*0,1.5,'1.5')
check('CPU',sum([2,4,6])/3,4,'return 4')
check('GPU',2*4,8,'(2, 4, 6, 8)')
check('Tensor core',1*3+2*4+5,16,'[[16]]')
check('CUDA',1*4+2,6,'= 6')
check('CUDA',8*4,32,'32 threads')
check('Compute cluster',20+60/4,35,'35 seconds')
check('Borehole logs and assays',102-100,2,'= 2 m')
check('Ore grade estimation',1000*.8/100,8,'= 8 tonnes')
check('Provenance and uncertainty',30-.2,29.8,'29.8')
check('Open source and reproducibility',sum([2,4,6])/3,4,'= 4')
check('Representation alignment',-math.log(.2),1.61,'≈ 1.61',tol=.001)
check('Representation alignment',-math.log(.8),.22,'≈ 0.22',tol=.005)
